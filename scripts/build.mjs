// 워커와 kordoc 렌더 경로를 dist/worker.mjs 하나로 묶고, 묶인 패키지의 라이선스를 THIRD_PARTY_NOTICES.txt로 모은다.
// 사용: node scripts/build.mjs   (검사만: node scripts/build.mjs --check → 커밋된 dist가 소스와 같은지 확인)
import { build } from 'esbuild'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = join(root, 'dist', 'worker.mjs')
const noticesFile = join(root, 'THIRD_PARTY_NOTICES.txt')
const typesFile = join(root, 'dist', 'worker.d.mts')
const TYPES = "// Generated by scripts/build.mjs. Types of the bundled worker for tests.\nimport type { OrcaWorkerApi } from 'orca/worker'\nexport default function activate(orca: OrcaWorkerApi): void\n"
const check = process.argv.includes('--check')

// kordoc의 OCR·PDF·래스터 선택 의존성: 렌더 경로는 쓰지 않으므로 번들에서 뺀다 (네이티브 바이너리 포함)
const OPTIONAL = [
  'onnxruntime-node',
  'puppeteer-core',
  'sharp',
  'zxing-wasm',
  'pdfjs-dist',
  '@hyzyla/pdfium',
  '@huggingface/tokenizers',
  'libheif-js'
]

const result = await build({
  entryPoints: [join(root, 'worker', 'main.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  outfile,
  metafile: true,
  legalComments: 'none',
  external: OPTIONAL,
  // CJS 의존성(jszip 등)의 require()가 ESM 번들에서도 동작하게 한다
  banner: {
    js: [
      '// Generated by scripts/build.mjs from worker/*.ts and the kordoc npm package. Do not edit.',
      "import { createRequire as __hwpCreateRequire } from 'node:module';",
      'const require = __hwpCreateRequire(import.meta.url);'
    ].join('\n')
  },
  logLevel: 'warning'
})

/** 번들에 실제로 들어간 npm 패키지 폴더 목록 */
function bundledPackages() {
  const output = Object.values(result.metafile.outputs)[0]
  const dirs = new Set()
  for (const [input, info] of Object.entries(output.inputs)) {
    if (info.bytesInOutput === 0) continue
    const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//)
    if (match) dirs.add(join(root, match[1]))
  }
  return [...dirs].sort()
}

/** 라이선스 파일, 없으면 README의 License 절 */
function licenseTexts(dir) {
  const files = readdirSync(dir).filter((name) => /^(licen[cs]e|copying|notice)/i.test(name))
  if (files.length > 0) return files.map((name) => readFileSync(join(dir, name), 'utf8').trim())
  const readme = readdirSync(dir).find((name) => /^readme/i.test(name))
  const section = readme && readFileSync(join(dir, readme), 'utf8').match(/^#+\s*licen[cs]e\s*\n([\s\S]*?)(?=^#+\s|(?![\s\S]))/im)
  if (section) return [section[1].trim().replace(/&lt;/g, '<').replace(/&gt;/g, '>')]
  throw new Error(`라이선스 문구를 찾지 못했습니다: ${dir}`)
}

function notices() {
  const parts = [
    'HWP Viewer (Orca plugin) bundles the following third-party software in dist/worker.mjs.',
    'Each entry lists the package, version, declared license and the license text it ships.',
    ''
  ]
  for (const dir of bundledPackages()) {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    parts.push('='.repeat(80), `${pkg.name}@${pkg.version} — ${pkg.license ?? 'see license text'}`)
    if (pkg.repository) parts.push(typeof pkg.repository === 'string' ? pkg.repository : pkg.repository.url)
    parts.push('', ...licenseTexts(dir))
    const thirdParty = join(dir, 'THIRD_PARTY')
    if (existsSync(thirdParty)) {
      for (const name of readdirSync(thirdParty).sort()) {
        parts.push('', `--- ${pkg.name}/THIRD_PARTY/${name} ---`, readFileSync(join(thirdParty, name), 'utf8').trim())
      }
    }
    parts.push('')
  }
  return `${parts.join('\n')}\n`
}

const code = result.outputFiles[0].text
const noticeText = notices()

if (check) {
  const same = (file, text) => existsSync(file) && readFileSync(file, 'utf8') === text
  const expected = new Map([[outfile, code], [noticesFile, noticeText], [typesFile, TYPES]])
  const stale = [...expected].filter(([file, text]) => !same(file, text)).map(([file]) => file)
  if (stale.length > 0) {
    console.error(`stale build output: ${stale.map((file) => relative(root, file)).join(', ')} — run npm run build`)
    process.exit(1)
  }
  console.log('build output is up to date')
} else {
  const { mkdirSync } = await import('node:fs')
  mkdirSync(dirname(outfile), { recursive: true })
  writeFileSync(outfile, code)
  writeFileSync(noticesFile, noticeText)
  writeFileSync(typesFile, TYPES)
  console.log(`wrote ${relative(root, outfile)} (${(code.length / 1024).toFixed(0)} KiB), ${bundledPackages().length} bundled packages`)
}
